"""Pydantic v2 schemas for the AI Threat Intelligence and Explanation layer."""

from enum import Enum
from typing import Literal

from pydantic import BaseModel, ConfigDict, Field

from app.schemas.threat_report import ThreatReport


class FallbackReason(str, Enum):
    """Machine-readable fallback trigger reason codes."""

    AI_DISABLED = "AI_DISABLED"
    MISSING_API_KEY = "MISSING_API_KEY"
    TIMEOUT = "TIMEOUT"
    NETWORK_ERROR = "NETWORK_ERROR"
    PROVIDER_ERROR = "PROVIDER_ERROR"
    RATE_LIMITED = "RATE_LIMITED"
    INVALID_JSON = "INVALID_JSON"
    SCHEMA_VALIDATION_FAILED = "SCHEMA_VALIDATION_FAILED"
    GROUNDING_VALIDATION_FAILED = "GROUNDING_VALIDATION_FAILED"
    CIRCUIT_OPEN = "CIRCUIT_OPEN"
    INPUT_REJECTED = "INPUT_REJECTED"


class ActionPriority(str, Enum):
    """Recommended action priority tiers."""

    HIGH = "high"
    MEDIUM = "medium"
    LOW = "low"


class AIConfidence(str, Enum):
    """Subjective confidence level of the generated explanation."""

    LOW = "low"
    MEDIUM = "medium"
    HIGH = "high"


class ExplanationSource(str, Enum):
    """Provenance indicator for transparent UI disclosure."""

    AI = "ai"
    DETERMINISTIC_FALLBACK = "deterministic_fallback"


class StrictAIModel(BaseModel):
    """Base model forbidding extra fields so unexpected LLM outputs fail schema validation."""

    model_config = ConfigDict(
        extra="forbid",
        validate_default=True,
    )


class KeyFinding(StrictAIModel):
    """Individual evidence-grounded key finding citing indicator IDs."""

    title: str = Field(..., max_length=250, description="Concise finding headline")
    detail: str = Field(..., max_length=1500, description="Plain language explanation")
    evidence_ids: list[str] = Field(
        default_factory=list, description="One or more cited evidence/indicator IDs"
    )


class RecommendedAction(StrictAIModel):
    """Prioritized defensive recommendation for the user."""

    priority: ActionPriority = Field(default=ActionPriority.MEDIUM, description="Action priority level")
    action: str = Field(..., max_length=1000, description="Defensive guidance statement")


class AIExplanation(StrictAIModel):
    """Structured, evidence-grounded explanation produced by LLM or deterministic fallback."""

    summary: str = Field(
        ..., max_length=2500, description="Plain-language threat summary"
    )
    risk_statement: str = Field(
        default="", max_length=1500, description="Risk narrative consistent with the deterministic risk level"
    )
    key_findings: list[KeyFinding] = Field(
        default_factory=list,
        max_length=8,
        description="List of cited key findings (up to 8 findings)",
    )
    recommended_actions: list[RecommendedAction] = Field(
        default_factory=list, description="Prioritized defensive recommended actions"
    )
    confidence: AIConfidence = Field(
        ..., description="Confidence assessment (low, medium, or high)"
    )
    limitations: list[str] = Field(
        default_factory=list, description="Technical and scope boundaries of the analysis"
    )
    disclaimer: str = Field(..., description="Mandatory advisory and safety disclaimer")


class ExplanationMeta(StrictAIModel):
    """Provenance and telemetry metadata for the explanation."""

    explanation_source: ExplanationSource = Field(..., description="Source of the explanation")
    model: str | None = Field(default=None, description="Model identifier if generated by AI")
    fallback_reason: FallbackReason | None = Field(
        default=None, description="Reason code if fallback was used"
    )
    prompt_injection_suspected: bool = Field(
        default=False, description="True if prompt injection heuristics triggered on untrusted text"
    )
    latency_ms: int = Field(
        default=0, ge=0, description="Total generation duration in milliseconds"
    )
    generated_at: str = Field(..., description="ISO 8601 UTC timestamp of generation")


class ExplanationResponse(StrictAIModel):
    """API response envelope for POST /api/v1/explanations."""

    explanation: AIExplanation
    meta: ExplanationMeta


class ExplainRequest(BaseModel):
    """Request payload for POST /api/v1/explanations."""

    model_config = ConfigDict(
        extra="ignore",
        validate_default=True,
    )

    report: ThreatReport = Field(..., description="Complete Phase 04 ThreatReport object")
    audience_level: Literal["simple", "technical"] = Field(
        default="simple", description="Audience depth: 'simple' or 'technical'"
    )


class AIStatusResponse(StrictAIModel):
    """Response envelope for GET /api/v1/ai/status."""

    ai_enabled: bool = Field(..., description="Whether AI feature is enabled in configuration")
    provider_configured: bool = Field(
        ..., description="Whether a valid provider API key is configured"
    )
    model: str | None = Field(default=None, description="Configured LLM model identifier")
